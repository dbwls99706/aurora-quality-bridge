"""Owner-only actual-PG budget QA. No adapter, provider, key or production budget.
Call only from the authenticated, persisted once-only owner QA route.
QA rows are retained as evidence; no existing workspace or marker is changed.
"""
from contextlib import contextmanager
from concurrent.futures import ThreadPoolExecutor

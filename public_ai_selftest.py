class QASQLProxy:
    def __init__(self, db, suffix):
        if not re.fullmatch('[0-9a-f]{16}', suffix):
            raise ValueError('Invalid QA table suffix')
        self.db=db
        self.names={name:'qa_'+name+'_'+suffix for name in ('public_ai_policy','public_ai_reservations')}
    def execute(self, sql, parameters=()):
        # Only exact schema-qualified identifiers generated by PublicAILedger.
        # Never rewrite values, marker/workspaces, schema or other identifiers.
        pattern=r'(?<![A-Za-z0-9_])'+re.escape(REG)+r'\.(public_ai_policy|public_ai_reservations)(?![A-Za-z0-9_])'
        sql=re.sub(pattern,lambda m:REG+'.'+self.names[m.group(1)],sql)
        return self.db.execute(sql,parameters)

class QALedger(PublicAILedger):
    def __init__(self, reg, expires_at, suffix):
        super().__init__(reg.config,expires_at=expires_at,connector=reg.connector,enabled=True,pricing_verified=True)
        self.suffix=suffix
    @contextmanager
    def connection(self):
        with registry_connection(self.config,self.connector) as db:
            yield QASQLProxy(db,self.suffix)

def ensure(value):
    if not value:raise AssertionError('Public AI PG QA mismatch')

def expect(code,fn):
    try:fn()
    except APIError as error:
        ensure(error.code==code);return
    raise AssertionError('Expected budget denial')

def create_qa_workspaces(reg, count=10):
    """Minimal synthetic ledger fixtures, no schema, token or public session.
    Capacity is enforced; short-lived fixtures remain and are never deleted.
    Does not call service actions or alter production rates/marker settings.
    """
    if count!=10:raise ValueError('Exactly ten QA fixtures required')
    with registry_connection(reg.config,reg.connector) as db:
        now=float(db.execute('SELECT extract(epoch FROM clock_timestamp())').fetchone()[0])
        marker=db.execute(f'SELECT app_id,expires,spaces FROM {REG}.marker WHERE id=1').fetchone()
        ensure(marker and marker[0]==reg.config.app_id and marker[1]>now+120)
        used=db.execute(f'SELECT count(*) FROM {REG}.workspaces').fetchone()[0]
        ensure(used+count<=marker[2])
        expiry=min(now+7200,marker[1]);ids=[]
        for _ in range(count):
            workspace=secrets.token_hex(16);ids.append(workspace)
            # Prefix cannot equal the SHA256 hash used for public cookie lookup.
            db.execute(f'INSERT INTO {REG}.workspaces VALUES(%s,%s,%s,%s,0,1)',(workspace,'qa-ai:'+secrets.token_hex(32),now,expiry))
    return ids,datetime.fromtimestamp(expiry,timezone.utc)

def run_public_ai_checks(reg):
    """Returns checks; caller persists once-only result. No actual AI calls.
    pricing_verified=True applies only to isolated mathematical test tables,
    and does not enable/verify pricing of the production AI adapter.
    """
    checks=[]
    def check(name,fn):
        try:fn();checks.append({'name':name,'status':'pass'})
        except Exception as error:checks.append({'name':name,'status':'fail','error_type':type(error).__name__})
    try:
        spaces,expiry=create_qa_workspaces(reg)
        suffix=secrets.token_hex(8)
        def new():return QALedger(reg,expiry,suffix)
        ledger=new();ledger.initialize();payload=hashlib.sha256(b'QA synthetic payload only').hexdigest()
        accepted=[]
        def concurrent():
            def attempt(i):
                try:return new().reserve(spaces[i], 'concurrent',payload)
                except APIError as error:ensure(error.code=='AI_BUSY');return None
            with ThreadPoolExecutor(max_workers=6) as pool:
                accepted.extend(x for x in pool.map(attempt,range(6)) if x)
            ensure(len(accepted)==2)
            ensure(new().status(spaces[0])['active_or_uncertain']==2)
        check('public_ai_pg_concurrency_two',concurrent)
        # If concurrency failed, never manufacture a passing later result.
        ensure(len(accepted)==2)
        def duplicate():
            with ledger.connection() as db:
                rows=db.execute(f'SELECT workspace,request_id FROM {REG}.public_ai_reservations').fetchall()
            ensure(len(rows)==2)
            workspace=rows[0][0]
            expect('AI_ALREADY_RESERVED',lambda:new().reserve(workspace,'concurrent',payload))
            expect('IDEMPOTENCY_CONFLICT',lambda:new().reserve(workspace,'concurrent','f'*64))
        check('public_ai_pg_idempotency',duplicate)
        for request in accepted:ledger.finish(request,'succeeded')
        def visitor():
            with ledger.connection() as db:
                workspace=db.execute(f'SELECT workspace FROM {REG}.public_ai_reservations LIMIT 1').fetchone()[0]
            request=new().reserve(workspace,'second',payload);new().finish(request,'definite_failure')
            expect('AI_VISITOR_LIMIT',lambda:new().reserve(workspace,'third',payload))
        check('public_ai_pg_visitor_two',visitor)
        def global_limit():
            for workspace in spaces:
                for j in range(2):
                    if new().status(workspace)['total_attempts_reserved']>=19:break
                    try:request=new().reserve(workspace,'fill-'+str(j),payload)
                    except APIError as error:ensure(error.code=='AI_VISITOR_LIMIT');break
                    new().finish(request,'succeeded')
            status=new().status(spaces[-1])
            ensure(status['total_attempts_reserved']==19 and status['remaining_global_attempts']==0)
            ensure(status['total_cost_reserved_usd']==19*RESERVATION/1_000_000)
            ensure(19*RESERVATION<=BUDGET<20*RESERVATION)
            expect('AI_USAGE_LIMIT',lambda:new().reserve(spaces[-1],'over-budget',payload))
        check('public_ai_pg_global_nineteen',global_limit)
        def restart():
            restarted=new();restarted.initialize()
            status=restarted.status(spaces[-1])
            ensure(status['ledger_readable'] and status['total_attempts_reserved']==19 and status['remaining_global_attempts']==0)
            expect('AI_USAGE_LIMIT',lambda:restarted.reserve(spaces[-1],'restart-over-budget',payload))
        check('public_ai_pg_fresh_instance_persistence',restart)
    except Exception as error:
        checks.append({'name':'public_ai_pg_setup','status':'fail','error_type':type(error).__name__})
    return checks

# Must remain behind parent's authenticated persisted once-only runner.
run_once = run_public_ai_checks
